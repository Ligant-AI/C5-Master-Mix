// C5-IV-04: the invariance tests confirmed capable of failing. A clamp, a
// floor and a nudge are inserted, one at a time, into the computation path of
// a scratch copy of the engine. For each, the record shows:
//   - which invariance tests fail (each defect must be detected), and
//   - how far the defect moves the unrounded results: the largest relative
//     difference from the unmutated engine over the seeded panels, which must
//     exceed the PROVISIONAL tolerance (open item 5).
// Writes verification/iv-04-record.md and prints it. Exit 1 if any defect is
// not detected or does not exceed the tolerance.
//
//   node verification/mutation/iv04.mjs
import { mkdtempSync, cpSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const FILE = 'src/engine/determine.js';

const DEFECTS = [
  ['clamp', 'each component\'s volume in the cocktail held up to the declared minimum transfer volume',
    'const vCocktail = vPerTest * nEff;', 'const vCocktail = Math.max(vPerTest * nEff, p.minTransfer.value);'],
  ['floor', 'each component\'s volume in the cocktail rounded down to 3 significant figures before use',
    'const vCocktail = vPerTest * nEff;', 'const vCocktail = ((x) => { const k = 10 ** (Math.floor(Math.log10(x)) - 2); return Math.floor(x / k) * k; })(vPerTest * nEff);'],
  ['nudge', 'each component\'s volume per test under preserve concentration multiplied by (1 + 2^-40)',
    'const vPerTest = s ? a * s.value : a;', 'const vPerTest = s ? a * s.value * (1 + 2 ** -40) : a;'],
];

const numbers = (x, out = []) => {
  if (typeof x === 'number') out.push(x);
  else if (Array.isArray(x)) x.forEach((y) => numbers(y, out));
  else if (x && typeof x === 'object') Object.values(x).forEach((y) => numbers(y, out));
  return out;
};

const { randomPanel } = await import(pathToFileURL(path.join(ROOT, 'tests/helpers/panels.js')));
const { determine: original } = await import(pathToFileURL(path.join(ROOT, FILE)));
const { TOLERANCES, relativeDifference } = await import(pathToFileURL(path.join(ROOT, 'src/engine/tolerances.js')));
const tolerance = TOLERANCES.roundTrip.relative;
const panels = [];
for (let seed = 1; panels.length < 400; seed++) {
  const input = randomPanel(seed);
  if (original(input).status === 'result') panels.push(input);
}

const scratch = mkdtempSync(path.join(tmpdir(), 'c5-iv04-'));
const rows = [];
let ok = true;
try {
  cpSync(ROOT, scratch, { recursive: true, filter: (src) => !/[/\\](\.git|dist)([/\\]|$)/.test(src) });
  const target = path.join(scratch, FILE);
  const source = readFileSync(target, 'utf8');
  for (const [name, what, from, to] of DEFECTS) {
    if (!source.includes(from)) throw new Error(`${name}: insertion point not found`);
    writeFileSync(target, source.replace(from, to));
    const run = spawnSync('node --test tests/determine.test.js', { cwd: scratch, encoding: 'utf8', shell: true });
    const out = `${run.stdout}${run.stderr}`;
    const failing = [...new Set([...out.matchAll(/^✖ (.+?) \([\d.]+ms\)$/gm)].map((m) => m[1]))];
    const { determine: mutated } = await import(`${pathToFileURL(target)}?${name}`);
    let largest = 0;
    let changed = 0;
    for (const input of panels) {
      const a = original(input);
      const b = mutated(input);
      if (b.status !== 'result') continue;
      const x = numbers(a.values);
      const y = numbers(b.values);
      let d = 0;
      for (let i = 0; i < x.length; i++) d = Math.max(d, relativeDifference(x[i], y[i]));
      if (d > 0) changed++;
      largest = Math.max(largest, d);
    }
    const detected = failing.length > 0;
    const exceeds = largest > tolerance;
    if (!detected || !exceeds) ok = false;
    rows.push({ name, what, to, failing, largest, changed, detected, exceeds });
    writeFileSync(target, source);
  }
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const lines = [
  '# C5-IV-04 record: the invariance tests confirmed capable of failing',
  '',
  'Generated by `node verification/mutation/iv04.mjs`. Each defect is inserted, alone, into `src/engine/determine.js` in a scratch copy outside the repository; `tests/determine.test.js` is run against it; and the defect\'s effect is measured as the largest relative difference of any unrounded value from the unmutated engine, over the same ' + panels.length + ' seeded panels the invariance tests use.',
  '',
  `Tolerance: ${tolerance} (2^-48), PROVISIONAL, open item 5 (\`src/engine/tolerances.js\`).`,
  '',
  '| Defect | Inserted | Detected by | Largest relative effect | Panels changed | Exceeds tolerance |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.what}: \`${r.to.replace(/\|/g, '\\|')}\` | ${r.failing.length ? r.failing.join('; ') : '**not detected**'} | ${r.largest} | ${r.changed} of ${panels.length} | ${r.exceeds ? 'yes' : '**no**'} |`),
  '',
  ok ? 'Every defect was detected, and every defect\'s effect exceeds the tolerance.' : '**At least one defect was not detected or did not exceed the tolerance.**',
  '',
];
writeFileSync(path.join(ROOT, 'verification/iv-04-record.md'), lines.join('\n'));
console.log(lines.join('\n'));
process.exit(ok ? 0 : 1);
